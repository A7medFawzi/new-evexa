import os
import re

ROOT = "."
PAGES = [
    "about",
    "contact",
    "portfolio",
    "privacy-policy",
    "terms-conditions",
    "portfolio-lemonide-tech",
    "portfolio-million-one",
    "portfolio-viper-studio",
]
TSX_PATH = {p: p for p in PAGES}
TSX_PATH.update({
    "portfolio-lemonide-tech": "portfolio/lemonide-tech",
    "portfolio-million-one": "portfolio/million-one",
    "portfolio-viper-studio": "portfolio/viper-studio",
})


def blocks(html, tag):
    """Non-nesting tag blocks as (start, end) spans."""
    out = []
    for m in re.finditer(r"<%s\b" % tag, html):
        close = "</%s>" % tag
        end = html.find(close, m.start())
        assert end > 0, f"unclosed <{tag}>"
        out.append((m.start(), end + len(close)))
    return out


def sig(html, spans, tag):
    """Breakpoint signature: the framer-v-* token of each block tag."""
    keys = []
    for s, e in spans:
        tagm = re.match(r"<%s[^>]*" % tag, html[s:e]).group(0)
        vm = re.search(r"framer-v-([A-Za-z0-9]+)", tagm)
        keys.append(vm.group(1) if vm else "?")
    return tuple(keys)


def sync_footers(lang):
    can_path = f"{ROOT}/src/content/body{'-ar' if lang == 'ar' else ''}.html"
    with open(can_path, "r", encoding="utf-8") as f:
        can = f.read()

    can_f_spans = blocks(can, "footer")
    assert len(can_f_spans) == 3, f"{lang} canonical footer count is {len(can_f_spans)}, expected 3"
    can_f_sig = sig(can, can_f_spans, "footer")
    can_footers = [can[s:e] for s, e in can_f_spans]

    for page in PAGES:
        p_path = f"{ROOT}/src/content/pages{'-ar' if lang == 'ar' else ''}/{page}.html"
        if not os.path.exists(p_path):
            print(f"Skipping {p_path} (does not exist)")
            continue

        with open(p_path, "r", encoding="utf-8") as f:
            html = f.read()

        f_spans = blocks(html, "footer")
        assert len(f_spans) == 3, f"{lang}/{page} footer count {len(f_spans)}, expected 3"
        assert sig(html, f_spans, "footer") == can_f_sig, f"{lang}/{page} footer signature mismatch"

        # replace from last to first so character offsets stay valid
        for (s, e), new in sorted(zip(f_spans, can_footers), key=lambda t: -t[0][0]):
            html = html[:s] + new + html[e:]

        with open(p_path, "w", encoding="utf-8") as f:
            f.write(html)
        print(f"{lang}/{page}: footers replaced and unified with homepage")


print("=== Syncing EN Footers ===")
sync_footers("en")

print("\n=== Syncing AR Footers ===")
sync_footers("ar")

# Polish CSS extraction
def extract_custom_rules(css):
    out, i, n, depth, rule_start = [], 0, len(css), 0, 0
    while i < n:
        c = css[i]
        if c == "{":
            depth += 1
        elif c == "}":
            depth -= 1
            if depth == 0:
                rule = css[rule_start:i + 1]
                if ("evx-" in rule) or ('[dir="rtl"]' in rule) or ("margin-inline-start" in rule):
                    out.append(rule.strip())
                rule_start = i + 1
        i += 1
    return out


with open(f"{ROOT}/src/app/evexa.css", "r", encoding="utf-8") as f:
    evexa = f.read()

rules = extract_custom_rules(evexa)
polish = "\n".join(rules) + "\n"

# Also append RTL arrow hover rule from ar-typography
rtl_arrow_rule = """
[dir="rtl"] .framer-8QOGx .framer-u628B:hover .evx-btn-arrow {
  transform: translate(-1px, -1px) !important;
}
"""
polish += rtl_arrow_rule

with open(f"{ROOT}/src/content/chrome-polish.css", "w", encoding="utf-8") as f:
    f.write("/* Shared footer/navbar polish — auto-extracted custom rules.\n"
            "   Auto-generated by scripts/unify_footers.py */\n" + polish)
print(f"\nchrome-polish.css updated with {len(rules)} custom rules + RTL arrow hover rule")

# Ensure subpages import chrome-polish.css
for page in PAGES:
    tsx = f"{ROOT}/src/app/[lang]/{TSX_PATH[page]}/page.tsx"
    if not os.path.exists(tsx):
        continue
    with open(tsx, "r", encoding="utf-8") as f:
        src = f.read()
    if "chrome-polish.css" not in src:
        m = re.search(r'import "@/content/pages/[^"]+\.css";', src)
        if m:
            src = src[:m.end()] + '\nimport "@/content/chrome-polish.css";' + src[m.end():]
            with open(tsx, "w", encoding="utf-8") as f:
                f.write(src)
            print(f"tsx/{page}: chrome-polish.css import added")
        else:
            print(f"tsx/{page}: css import marker not found")
    else:
        print(f"tsx/{page}: already imports chrome-polish.css")

# Final verification
all_ok = True
for lang in ("en", "ar"):
    suffix = "-ar" if lang == "ar" else ""
    with open(f"{ROOT}/src/content/body{suffix}.html", "r", encoding="utf-8") as f:
        can = f.read()
    can_f = [can[s:e] for s, e in blocks(can, "footer")]
    for page in PAGES:
        p_path = f"{ROOT}/src/content/pages{suffix}/{page}.html"
        with open(p_path, "r", encoding="utf-8") as f:
            p = f.read()
        p_f = [p[s:e] for s, e in blocks(p, "footer")]
        is_identical = (p_f == can_f)
        if not is_identical:
            all_ok = False
        print(f"[{'PASS' if is_identical else 'FAIL'}] {lang}/{page}: footer is 100% identical to homepage")

if all_ok:
    print("\nSUCCESS: All footers across all EN and AR subpages are 100% byte-identical to the homepage footer!")
else:
    print("\nWARNING: Some footers did not match.")

